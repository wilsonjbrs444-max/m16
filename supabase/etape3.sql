-- Les clients ne peuvent plus créer de commande "à la main" : tout passe par place_order,
-- qui recalcule les prix côté base et vérifie le stock.
drop policy if exists "commandes: créer" on public.orders;
drop policy if exists "lignes: créer" on public.order_items;

create or replace function public.place_order(p_items jsonb, p_name text, p_phone text, p_address text, p_method text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_order public.orders;
  v_total integer := 0;
  v_prod public.products;
  v_qty integer;
  it jsonb;
begin
  if v_uid is null then raise exception 'Connexion requise'; end if;
  if p_items is null or jsonb_array_length(p_items) = 0 then raise exception 'Votre panier est vide'; end if;
  if coalesce(trim(p_name), '') = '' or coalesce(trim(p_phone), '') = '' or coalesce(trim(p_address), '') = '' then
    raise exception 'Nom, téléphone et adresse sont obligatoires';
  end if;
  if p_method not in ('MTN MoMo', 'Orange Money', 'Paiement à la livraison', 'WhatsApp') then
    raise exception 'Mode de paiement invalide';
  end if;

  insert into public.orders (user_id, total, payment_method, customer_name, phone, address, status)
  values (v_uid, 0, p_method, trim(p_name), trim(p_phone), trim(p_address),
          case when p_method in ('MTN MoMo', 'Orange Money') then 'Payée' else 'En attente' end)
  returning * into v_order;

  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := (it->>'qty')::int;
    if v_qty is null or v_qty < 1 then raise exception 'Quantité invalide'; end if;
    select * into v_prod from public.products where id = (it->>'id')::uuid and active for update;
    if not found then raise exception 'Un article de votre panier n''est plus disponible'; end if;
    if v_prod.stock < v_qty then raise exception 'Stock insuffisant pour %', v_prod.name; end if;
    update public.products set stock = stock - v_qty where id = v_prod.id;
    insert into public.order_items (order_id, product_id, name, price, qty)
    values (v_order.id, v_prod.id, v_prod.name, v_prod.price, v_qty);
    v_total := v_total + v_prod.price * v_qty;
  end loop;

  update public.orders set total = v_total where id = v_order.id;
  return jsonb_build_object('id', v_order.id, 'number', v_order.number, 'total', v_total);
end $$;
revoke all on function public.place_order(jsonb, text, text, text, text) from public;
grant execute on function public.place_order(jsonb, text, text, text, text) to authenticated;

-- Une commande annulée remet les articles en stock.
create or replace function public.restock_on_cancel() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'Annulée' and old.status <> 'Annulée' then
    update public.products p set stock = p.stock + oi.qty
    from public.order_items oi where oi.order_id = new.id and oi.product_id = p.id;
  end if;
  return new;
end $$;
drop trigger if exists orders_restock on public.orders;
create trigger orders_restock after update of status on public.orders
for each row execute function public.restock_on_cancel();
